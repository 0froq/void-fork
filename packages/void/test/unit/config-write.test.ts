import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { afterEach, describe, expect, it } from 'vite-plus/test';
import { canRewriteVoidProjectConfig, writeVoidProjectConfig } from '../../src/config-write.ts';
import { readConfig } from '../../src/config.ts';

const root = join(import.meta.dirname, '.tmp-config-write-test');

function setup(source: string): void {
  rmSync(root, { recursive: true, force: true });
  mkdirSync(root, { recursive: true });
  writeFileSync(join(root, 'void.config.ts'), source);
}

afterEach(() => rmSync(root, { recursive: true, force: true }));

describe('writeVoidProjectConfig', () => {
  it('updates a formatter-styled generated config without losing other fields', () => {
    setup(
      "// Generated by void migrate.\nimport { defineConfig } from 'void/config';\n\nexport default defineConfig({\n  worker: { compatibility_date: '2026-02-24' },\n  routing: { isr: false },\n  cloudflare: { vars: { CUSTOM: 'yes' } },\n});\n",
    );

    writeVoidProjectConfig(root, {
      ...readConfig(root),
      routing: { isr: true },
    });
    expect(readConfig(root)).toEqual({
      worker: { compatibility_date: '2026-02-24' },
      routing: { isr: true },
      cloudflare: { vars: { CUSTOM: 'yes' } },
    });
  });

  it('refuses expressions and comments in authored TypeScript', () => {
    setup(
      "// Generated by void migrate.\nimport { defineConfig } from 'void/config';\nexport default defineConfig({ remote: process.env.REMOTE === '1' });\n",
    );
    const original = readFileSync(join(root, 'void.config.ts'), 'utf8');
    expect(() => writeVoidProjectConfig(root, { remote: false })).toThrow('authored TypeScript');
    expect(canRewriteVoidProjectConfig(root)).toBe(false);
    expect(readFileSync(join(root, 'void.config.ts'), 'utf8')).toBe(original);

    setup(
      "// Generated by void migrate.\nimport { defineConfig } from 'void/config';\nexport default defineConfig({ /* keep */ remote: true });\n",
    );
    expect(() => writeVoidProjectConfig(root, { remote: false })).toThrow('authored TypeScript');
  });

  it('recognizes parenthesized static values and comment-like strings', () => {
    setup(
      "// Generated by void init.\nimport { defineConfig } from 'void/config';\nexport default (defineConfig({ cloudflare: { vars: { URL: 'https://example.com', TEXT: '/* keep */', VALUES: [null, -1, true, 'text'] } }, remote: (false) }));\n",
    );

    expect(canRewriteVoidProjectConfig(root)).toBe(true);
    const config = readConfig(root);
    writeVoidProjectConfig(root, config);
    expect(readConfig(root)).toEqual(config);
  });

  it.each([
    ['type arguments', 'defineConfig<{ remote: boolean }>({ remote: false })'],
    ['type assertions', 'defineConfig({ remote: false } as const)'],
    ['syntax errors', 'defineConfig({ remote: true remote: false })'],
    ['strict-mode errors', 'defineConfig({ cloudflare: { vars: { COUNT: 01 } } })'],
    ['duplicate prototypes', 'defineConfig({ __proto__: null, __proto__: null })'],
  ])('preserves config containing %s', (_label, expression) => {
    const source = `// Generated by void init.\nimport { defineConfig } from 'void/config';\nexport default ${expression};\n`;
    setup(source);

    expect(canRewriteVoidProjectConfig(root)).toBe(false);
    expect(() => writeVoidProjectConfig(root, { remote: false })).toThrow('authored TypeScript');
    expect(readFileSync(join(root, 'void.config.ts'), 'utf8')).toBe(source);
  });
});
