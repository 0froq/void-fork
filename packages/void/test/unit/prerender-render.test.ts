import { existsSync, mkdtempSync, readFileSync, rmSync, statSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { afterEach, describe, expect, it } from 'vite-plus/test';
import { renderPrerenderPaths } from '../../src/prerender-render.ts';
import { createAssetFallback } from '../../src/runtime/routing-worker.ts';

const roots: Array<string> = [];
const fixture = () => {
  const root = mkdtempSync(join(tmpdir(), 'void-render-pool-'));
  roots.push(root);
  return root;
};
afterEach(() => {
  for (const root of roots.splice(0)) {
    rmSync(root, { recursive: true, force: true });
  }
});

describe('prerender pool', () => {
  it('bounds overlapping renders, keeps result order, and writes each page data after its HTML', async () => {
    const root = fixture();
    const paths = Array.from({ length: 12 }, (_, i) => `/page-${i}`);
    let active = 0;
    let peak = 0;
    const htmlDone = new Set<string>();
    const result = await renderPrerenderPaths(
      paths,
      root,
      async (path) => {
        peak = Math.max(peak, ++active);
        await new Promise((resolve) => setTimeout(resolve, path === '/page-0' ? 12 : 2));
        active--;
        htmlDone.add(path);
        return new Response(path, { status: path === '/page-3' ? 503 : 200 });
      },
      async (path) => {
        expect(htmlDone.has(path)).toBe(true);
        expect(readFileSync(join(root, `${path.slice(1)}.html`), 'utf8')).toBe(path);
        return Response.json({ path }, { headers: { 'X-VoidPages': 'true' } });
      },
    );
    expect(peak).toBe(4);
    expect(result.rendered).toEqual(paths.filter((path) => path !== '/page-3'));
    expect(result.failed).toEqual([{ path: '/page-3', error: 'HTTP 503' }]);
    expect(JSON.parse(readFileSync(join(root, '_void/pages/page-11.json'), 'utf8'))).toEqual({
      path: '/page-11',
    });
  });

  it.each([
    ['/', '/index'],
    ['/same', '/same'],
    ['/Page', '/page'],
    ['/a', '/a.html/b'],
  ])('preserves serial execution for colliding outputs %j', async (...paths) => {
    let active = 0;
    let peak = 0;
    const root = fixture();
    const result = await renderPrerenderPaths(paths, root, async (path) => {
      peak = Math.max(peak, ++active);
      await new Promise((resolve) => setTimeout(resolve, 2));
      active--;
      return new Response(path);
    });
    expect(peak).toBe(1);
    if (paths[0] === '/') {
      expect(result.rendered).toEqual(paths);
      expect(readFileSync(join(root, 'index.html'), 'utf8')).toBe('/index');
    }
    if (paths[0] === '/a') {
      expect(result.rendered).toEqual(['/a']);
      expect(result.failed.map((failure) => failure.path)).toEqual(['/a.html/b']);
    }
  });

  it.each([
    ['/foo', '/foo.html'],
    ['/guide/index', '/guide'],
    ['/encoded#asset', '/encoded%23asset.html'],
  ])(
    'preserves generated-asset fallthrough semantics between %s and %s',
    async (generatedPath, fallbackPath) => {
      const root = fixture();
      const serveWithAssets = createAssetFallback();
      const assets = {
        async fetch(request: Request): Promise<Response> {
          let file = join(root, decodeURIComponent(new URL(request.url).pathname));
          if (existsSync(file) && statSync(file).isDirectory()) {
            file = join(file, 'index.html');
          }
          try {
            return new Response(readFileSync(file), { status: 200 });
          } catch {
            return new Response('missing', { status: 404 });
          }
        },
      };
      const result = await renderPrerenderPaths(
        [generatedPath, fallbackPath],
        root,
        async (path) => {
          if (path === generatedPath) {
            await new Promise((resolve) => setTimeout(resolve, 10));
            return new Response(`generated by ${path}`);
          }
          return serveWithAssets(
            new Request(`https://app.test${path}`),
            { ASSETS: assets },
            new Response('route missing', { status: 404 }),
          );
        },
      );
      expect(result).toEqual({ rendered: [generatedPath, fallbackPath], failed: [] });
      expect(readFileSync(join(root, `${fallbackPath.slice(1)}.html`), 'utf8')).toBe(
        `generated by ${generatedPath}`,
      );
    },
  );
});
