// Build script for the sandbox host bundle.
// Bundles packages/api/src/provisioning/sandbox-host-source/index.ts into a
// single ESM module and writes the result to
// packages/api/src/provisioning/sandbox-host-bundle.generated.ts.
//
// Run via: pnpm -C packages/api build:sandbox-host

import { execSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, mkdirSync, rmSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'tsdown';

const __dirname = dirname(fileURLToPath(import.meta.url));
const pkgDir = join(__dirname, '..');
const sourceFile = join(pkgDir, 'src/provisioning/sandbox-host-source/index.ts');
const outDir = join(pkgDir, '.sandbox-host-tmp');
const outFile = join(outDir, 'index.js');
const generatedFile = join(pkgDir, 'src/provisioning/sandbox-host-bundle.generated.ts');

const COMPATIBILITY_DATE = '2026-02-12';

// Clean temp output dir
rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });

// Bundle using tsdown programmatic API:
// - Format: esm
// - Platform: neutral (not 'node' — workerd is not Node)
// - Externals: cloudflare:* and node:* (workerd runtime-provided builtins)
// - Bundle ALL npm deps (including @cloudflare/sandbox and its transitive deps)
//   via deps.neverBundle matching only cloudflare: and node: prefixes
// - No sourcemaps, no dts
// - Treeshake enabled (default)
await build({
  entry: [sourceFile],
  format: 'esm',
  platform: 'neutral',
  outDir,
  dts: false,
  sourcemap: false,
  treeshake: true,
  config: false, // don't pick up tsdown.config.ts
  deps: {
    // Only treat cloudflare:* and node:* as external — these are workerd/Node
    // builtins provided at runtime. All npm packages (including @cloudflare/sandbox)
    // must be bundled so the uploaded script is self-contained.
    neverBundle: (id: string) => id.startsWith('cloudflare:') || id.startsWith('node:'),
    // Force all other deps (specifically @cloudflare/sandbox + its deps) to be bundled.
    alwaysBundle: () => true,
  },
});

// Read the bundled output
const bundleString = readFileSync(outFile, 'utf-8');

// Compute SHA256
const sha256 = createHash('sha256').update(bundleString, 'utf-8').digest('hex');

// Emit using JSON.stringify for the string literal — avoids ${ } interpolation issues
// in template literals when the bundled code contains ${...} sequences.
const serialized = JSON.stringify(bundleString);

const generated = `// GENERATED by scripts/build-sandbox-host.ts — DO NOT EDIT.
// Regenerate via: pnpm -C packages/api build:sandbox-host
export const BUNDLE_BYTES = ${serialized};
export const BUNDLE_SHA256 = "${sha256}";
export const COMPATIBILITY_DATE = "${COMPATIBILITY_DATE}";
`;

writeFileSync(generatedFile, generated, 'utf-8');

// Format the generated file so it matches pre-commit hook output (oxfmt --write).
// This ensures `git diff --exit-code` stays clean after a rebuild.
execSync(`pnpm exec oxfmt --write ${generatedFile}`, { stdio: 'inherit' });

// Cleanup temp dir
rmSync(outDir, { recursive: true, force: true });

console.log(`Written: ${generatedFile}`);
console.log(`SHA256: ${sha256}`);
console.log(`Bundle size: ${(bundleString.length / 1024).toFixed(1)} KB`);
