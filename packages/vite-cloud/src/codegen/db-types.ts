import type { SchemaMap, ColumnDef } from "../migrations/schema";

/**
 * Generate .vite-cloud/db.d.ts content.
 * Uses `declare module` augmentation, same pattern as route-types.ts.
 */
export function generateDbTypes(schema: SchemaMap): string {
  const lines: string[] = [];

  lines.push("// Auto-generated by vite-cloud — do not edit");
  // `export {}` makes this a module so `declare module` is an augmentation
  // (merges with the resolved module) rather than an ambient declaration
  // (which would replace it and hide runtime exports like `db` and `createDb`).
  lines.push("export {}");
  lines.push('declare module "vite-cloud/db" {');
  lines.push("  interface DbTables {");

  for (const [, table] of schema) {
    lines.push(`    ${safeKey(table.name)}: {`);
    for (const col of table.columns) {
      const tsType = columnToTsType(col);
      lines.push(`      ${safeKey(col.name)}: ${tsType};`);
    }
    lines.push("    };");
  }

  lines.push("  }");
  lines.push("  interface DbInsertTables {");

  for (const [, table] of schema) {
    lines.push(`    ${safeKey(table.name)}: {`);
    for (const col of table.columns) {
      const tsType = columnToTsType(col);
      const optional = col.hasDefault || col.primaryKey;
      lines.push(`      ${safeKey(col.name)}${optional ? "?" : ""}: ${tsType};`);
    }
    lines.push("    };");
  }

  lines.push("  }");
  lines.push("}");
  lines.push("");

  return lines.join("\n");
}

function columnToTsType(col: ColumnDef): string {
  let base: string;
  switch (col.type) {
    case "INTEGER":
    case "REAL":
      base = "number";
      break;
    case "TEXT":
      base = "string";
      break;
    case "BLOB":
      base = "ArrayBuffer";
      break;
  }
  return col.nullable ? `${base} | null` : base;
}

function safeKey(name: string): string {
  return /^[a-zA-Z_$][a-zA-Z0-9_$]*$/.test(name) ? name : JSON.stringify(name);
}
