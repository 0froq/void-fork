import { relative } from "node:path";
import type { QueueDefinition } from "../queues/scan";

/**
 * Generate .vite-cloud/queues.d.ts content.
 *
 * Augments `vite-cloud/queues` with a typed `QueueMap` interface
 * so `queues.emails.send(body)` is fully typed from the consumer's
 * `defineQueue<T>` phantom type.
 */
export function generateQueueTypes(
  queues: QueueDefinition[],
  queuesDir: string,
  outDir: string,
): string {
  const lines: string[] = [];
  lines.push("// Auto-generated by vite-cloud — do not edit");
  lines.push("export {}");
  lines.push('declare module "vite-cloud/queues" {');
  lines.push("  interface QueueMap {");

  for (const q of queues) {
    const absPath = `${queuesDir}/${q.filePath}`;
    const relPath = relative(outDir, absPath).replace(/\\/g, "/");
    const importPath = relPath.replace(/\.(ts|mts|js|mjs)$/, "");

    lines.push(
      `    ${JSON.stringify(q.name)}: Queue<(typeof import(${JSON.stringify(importPath)}))["default"]["__payload"]>;`,
    );
  }

  lines.push("  }");
  lines.push("}");
  lines.push("");
  return lines.join("\n");
}
