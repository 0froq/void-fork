import fs from "node:fs";
import path from "node:path";
import type { DocPage } from "../src/types.js";

const docsDir = path.resolve(import.meta.dirname, "../../website/docs");
const outFile = path.resolve(import.meta.dirname, "../src/docs.ts");

export function buildDocs(): DocPage[] {
  const files = fs
    .readdirSync(docsDir)
    .filter((f) => f.endsWith(".md"))
    .sort();

  return files.map((file) => {
    let content = fs.readFileSync(path.join(docsDir, file), "utf-8");

    // Strip YAML frontmatter
    content = content.replace(/^---\n[\s\S]*?\n---\n/, "");

    // Extract title from first heading
    const titleMatch = content.match(/^#\s+(.+)/m);
    const title = titleMatch ? titleMatch[1].trim() : file.replace(/\.md$/, "");

    const slug = file.replace(/\.md$/, "");

    return { slug, title, content };
  });
}

if (process.argv.includes("--write")) {
  const pages = buildDocs();
  const code = `// Auto-generated by scripts/build-docs.ts — do not edit
import type { DocPage } from "./types.js";

export const docs: DocPage[] = ${JSON.stringify(pages, null, 2)};
`;

  fs.writeFileSync(outFile, code);
  console.log(`Generated src/docs.ts with ${pages.length} pages`);
}
